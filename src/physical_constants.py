"""
physical_constants.py — 物理常数与单位转换

统一使用单位: km, s, kg
参考系: J2000 黄道面
所有数据来源: JPL/NASA 标准值

使用方法:
    from physical_constants import *
"""

import numpy as np

# ============================================================
# 引力参数 μ (km³/s²)
# ============================================================
MU_SUN   = 1.32712440018e11   # 太阳
MU_EARTH = 3.986004418e5      # 地球
MU_MOON  = 4.9048695e3        # 月球

# ============================================================
# 天体半径 (km)
# ============================================================
R_SUN   = 6.957e5             # 太阳平均半径
R_EARTH = 6378.137            # 地球赤道半径
R_MOON  = 1737.4              # 月球平均半径

# ============================================================
# 轨道参数
# ============================================================
AU = 1.495978707e8            # 天文单位 (km)

# 地球绕太阳 (J2000 近似)
R_EARTH_ORBIT = AU            # 地球轨道半径 ≈ 1 AU
V_EARTH_ORBIT = np.sqrt(MU_SUN / R_EARTH_ORBIT)  # 地球轨道速度 ≈ 29.78 km/s

# 月球绕地球
R_MOON_ORBIT = 384400.0       # 月球轨道半长轴 (km)
V_MOON_ORBIT = np.sqrt(MU_EARTH / R_MOON_ORBIT)  # 月球轨道速度 ≈ 1.02 km/s

# 月球 SOI 半径 (km)
R_MOON_SOI = 6.6e4            # ≈ 66000 km

# 地球 SOI 半径 (km)
R_EARTH_SOI = 9.24e5          # ≈ 924000 km

# ============================================================
# 地球表面发射
# ============================================================
V_EARTH_ESCAPE = np.sqrt(2.0 * MU_EARTH / R_EARTH)  # 逃逸速度 ≈ 11.19 km/s
V_EARTH_ROTATION = 0.4651     # 赤道自转线速度 (km/s)，提供微小助力

# ============================================================
# N 体归一化参数 (μ=4π² 制，用于 M2 二体基准测试)
# ============================================================
# 在此单位制下:
#   长度单位 = AU
#   时间单位 = year / (2π)  即 1 TU = 58.13244 天
#   使得 μ_sun = 4π²

MU_NORM = 4.0 * np.pi**2     # 归一化后的太阳引力参数

# ============================================================
# 时间常数
# ============================================================
SECONDS_PER_DAY = 86400.0
SECONDS_PER_YEAR = 365.25 * SECONDS_PER_DAY

# ============================================================
# 约束边界 (来自 PROJECT_SPEC)
# ============================================================
C_RM_MIN = R_MOON + 100.0     # 1838 km, 不撞月球
C_RM_MAX = 50000.0            # km
C_RP_MIN = 2.0 * R_SUN        # 1.3914e6 km, 不撞太阳
C_RP_MAX = 0.4 * R_EARTH_ORBIT  # 0.4 AU
C_T_MAX = 2.0 * SECONDS_PER_YEAR  # 总飞行时间 ≤ 2 年
C_VINF_MAX = 15.0             # 再入 v∞ ≤ 15 km/s
C_ENERGY_TOL = 1e-6           # N 体能量相对误差
